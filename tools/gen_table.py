"""Regenerates src/table.rs from MAVLink's message_definitions (all.xml and
everything it includes), computing CRC_EXTRA the way the MAVLink generators do.

    python tools/gen_table.py path/to/message_definitions/v1.0
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

SIZE = {"char": 1, "uint8_t": 1, "int8_t": 1, "uint16_t": 2, "int16_t": 2,
        "uint32_t": 4, "int32_t": 4, "float": 4, "uint64_t": 8, "int64_t": 8,
        "double": 8, "uint8_t_mavlink_version": 1}


def acc(b, crc):
    t = (b ^ (crc & 0xFF)) & 0xFF
    t = (t ^ (t << 4)) & 0xFF
    return ((crc >> 8) ^ (t << 8) ^ (t << 3) ^ (t >> 4)) & 0xFFFF


def acc_str(s, crc):
    for b in s.encode():
        crc = acc(b, crc)
    return crc


def main(root):
    msgs, seen = {}, set()

    def load(name):
        if name in seen:
            return
        seen.add(name)
        tree = ET.parse(os.path.join(root, name)).getroot()
        for inc in tree.findall("include"):
            load(inc.text.strip())
        for m in tree.iter("message"):
            fields, ext = [], False
            for ch in m:
                if ch.tag == "extensions":
                    ext = True
                elif ch.tag == "field":
                    base, n = ch.get("type"), None
                    arr = re.match(r"(\w+)\[(\d+)\]", base)
                    if arr:
                        base, n = arr.group(1), int(arr.group(2))
                    fields.append((base, ch.get("name"), n, ext))
            core = sorted((f for f in fields if not f[3]), key=lambda f: -SIZE[f[0]])
            crc = acc_str(m.get("name") + " ", 0xFFFF)
            for base, fname, n, _ in core:
                crc = acc_str(("uint8_t" if base == "uint8_t_mavlink_version" else base) + " ", crc)
                crc = acc_str(fname + " ", crc)
                if n is not None:
                    crc = acc(n, crc)
            max_len = sum(SIZE[b] * (n or 1) for b, _, n, _ in fields)
            msgs.setdefault(int(m.get("id")), ((crc & 0xFF) ^ (crc >> 8), max_len, m.get("name")))

    load("all.xml")
    out = [
        "//! MAVLink message table: id, CRC_EXTRA, maximum payload length and name.",
        "//!",
        "//! Generated by tools/gen_table.py from MAVLink's `all.xml` dialect, which",
        "//! includes common, ardupilotmega, development and the vendor sets.",
        "//! Do not edit by hand.",
        "",
        "/// `(message id, CRC_EXTRA, maximum payload length, name)`, sorted by id.",
        "pub static MESSAGES: &[(u32, u8, u8, &str)] = &[",
    ]
    out += [f'    ({i}, {c}, {n}, "{name}"),' for i, (c, n, name) in sorted(msgs.items())]
    out.append("];")
    with open("src/table.rs", "w", newline="") as f:
        f.write("\n".join(out) + "\n")
    print(len(msgs), "messages")


if __name__ == "__main__":
    main(sys.argv[1])
